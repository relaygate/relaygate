func ClusterName(server, protocol string) string {
	return fmt.Sprintf("cluster-%s-%s-game", server, strings.ToLower(protocol))
}

func ListenerName(ruleName string) string {
	return "listener-" + ruleName
}

func Render(r *assets.Resources) (map[string]any, string, error) {
	if err := r.Validate(); err != nil {
		return nil, "", err
	}
	servers := r.ServerMap()
	rules := r.EnabledRules()
	defaults := r.Defaults
	listenAddress := r.Gateway.ListenAddress

	clusters := map[string]any{}
	var listeners []any

	for _, rule := range rules {
		server := servers[rule.Server]
		proto := strings.ToUpper(rule.Protocol)
		cname := ClusterName(server.Name, proto)
		if _, ok := clusters[cname]; !ok {
			if proto == "TCP" {
				clusters[cname] = renderTCPCluster(server, defaults)
			} else {
				clusters[cname] = renderUDPCluster(server, defaults)
			}
		}
		if proto == "TCP" {
			listeners = append(listeners, renderTCPListener(rule, listenAddress, defaults))
		} else {
			listeners = append(listeners, renderUDPListener(rule, listenAddress, defaults))
		}
	}

	clusterList := make([]any, 0, len(clusters))
	names := make([]string, 0, len(clusters))
	for n := range clusters {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		clusterList = append(clusterList, clusters[n])
	}

	cfg := map[string]any{
		"admin": map[string]any{
			"address": map[string]any{
				"socket_address": map[string]any{
					"protocol":   "TCP",
					"address":    r.Meta.AdminAddress,
					"port_value": r.Meta.AdminPort,
				},
			},
			"access_log": []any{
				map[string]any{
					"name": "envoy.access_loggers.file",
					"typed_config": map[string]any{
						"@type": "type.googleapis.com/envoy.extensions.access_loggers.file.v3.FileAccessLog",
						"path":  "/var/log/envoy/admin-access.log",
					},
				},
			},
		},
		"static_resources": map[string]any{
			"listeners": listeners,
			"clusters":  clusterList,
		},
	}
	return cfg, renderNFT(rules), nil
}

func Write(envoyPath, nftPath string, r *assets.Resources) error {
	cfg, nft, err := Render(r)
	if err != nil {
		return err
	}
	if err := assets.EnsureDir(envoyPath); err != nil {
		return err
	}
	if err := assets.EnsureDir(nftPath); err != nil {
		return err
	}
	body, err := yaml.Marshal(cfg)
	if err != nil {
		return err
	}
	header := "# Generated by gateway-render. Do not edit.\n# Source: config/resources.yaml\n"
	if err := os.WriteFile(envoyPath, append([]byte(header), body...), 0o644); err != nil {
		return err
	}
	return os.WriteFile(nftPath, []byte(nft), 0o644)
}

func renderTCPCluster(server assets.Server, d assets.Defaults) map[string]any {
	name := ClusterName(server.Name, "TCP")
	hcPort := server.HealthCheckPort
	if hcPort == 0 {
		hcPort = server.TCPPort
	}
	return map[string]any{
		"name":            name,
		"type":            "STATIC",
		"connect_timeout": "2s",
		"lb_policy":       "ROUND_ROBIN",
		"circuit_breakers": map[string]any{
			"thresholds": []any{
				map[string]any{
					"priority":             "DEFAULT",
					"max_connections":      d.MaxConnections,
					"max_pending_requests": d.MaxPendingRequests,
					"max_requests":         d.MaxConnections,
				},
			},
		},
		"health_checks": []any{
			map[string]any{
				"timeout":             d.HealthCheck.Timeout,
				"interval":            d.HealthCheck.Interval,
				"unhealthy_threshold": d.HealthCheck.UnhealthyThreshold,
				"healthy_threshold":   d.HealthCheck.HealthyThreshold,
				"tcp_health_check":    map[string]any{},
			},
		},
		"load_assignment": map[string]any{
			"cluster_name": name,
			"endpoints": []any{
				map[string]any{
					"lb_endpoints": []any{
						map[string]any{
							"endpoint": map[string]any{
								"address": map[string]any{
									"socket_address": map[string]any{
										"address":    server.Address,
										"port_value": server.TCPPort,
									},
								},
								"health_check_config": map[string]any{
									"port_value": hcPort,
								},
							},
						},
					},
				},
			},
		},
	}
}

