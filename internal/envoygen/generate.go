func renderNFT(rules []assets.Rule) string {
	tcpSet := map[int]struct{}{}
	udpSet := map[int]struct{}{}
	for _, r := range rules {
		switch strings.ToUpper(r.Protocol) {
		case "TCP":
			tcpSet[r.ListenPort] = struct{}{}
		case "UDP":
			udpSet[r.ListenPort] = struct{}{}
		}
	}
	tcp := sortedPorts(tcpSet)
	udp := sortedPorts(udpSet)
	if len(tcp) == 0 {
		tcp = []int{10001}
	}
	if len(udp) == 0 {
		udp = []int{10001}
	}
	return fmt.Sprintf(`# Generated by gateway-render. Do not edit.
# TCP game ports
define GAME_TCP_PORTS = { %s }
# UDP game ports
define GAME_UDP_PORTS = { %s }
`, joinInts(tcp), joinInts(udp))
}

func sortedPorts(set map[int]struct{}) []int {
	out := make([]int, 0, len(set))
	for p := range set {
		out = append(out, p)
	}
	sort.Ints(out)
	return out
}

func joinInts(ports []int) string {
	parts := make([]string, len(ports))
	for i, p := range ports {
		parts[i] = fmt.Sprintf("%d", p)
	}
	return strings.Join(parts, ", ")
}

func Summarize(r *assets.Resources) string {
	servers := r.ServerMap()
	rules := r.EnabledRules()
	var b strings.Builder
	fmt.Fprintf(&b, "校验通过: %d 台服务器, %d 条启用规则\n", len(servers), len(rules))
	for _, rule := range rules {
		fmt.Fprintf(&b, "  - %s: %s/%d -> %s (%s)\n",
			rule.Name, strings.ToUpper(rule.Protocol), rule.ListenPort, rule.Server, rule.Kind)
	}
	return b.String()
}
